--      Recomendado en la config del bucket: límite de tamaño ~20MB y mime
--      types permitidos image/*, video/mp4, video/quicktime.
--   2. Correr el SQL de abajo.

create table if not exists public.momentos_photos (
  id bigint generated by default as identity primary key,
  src text not null, -- URL pública de la imagen (o del poster si es video)
  video text, -- URL pública del video; null si la entrada es solo una foto
  caption text not null default '' check (char_length(caption) <= 120),
  created_at timestamptz not null default now()
);

alter table public.momentos_photos enable row level security;

create policy "public can read momentos"
  on public.momentos_photos
  for select
  to anon
  using (true);

create policy "public can insert momentos"
  on public.momentos_photos
  for insert
  to anon
  with check (true);

-- Permite subir archivos al bucket "momentos" desde el cliente (anon).
create policy "public can upload to momentos bucket"
  on storage.objects
  for insert
  to anon
  with check (bucket_id = 'momentos');
